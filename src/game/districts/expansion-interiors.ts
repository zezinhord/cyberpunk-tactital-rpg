function rectangleTiles(rects:readonly (readonly [number,number,number,number])[]):readonly Tile[]{
 return rects.flatMap(([x,y,w,h])=>Array.from({length:w*h},(_,i)=>({
  x:x+i%w,y:y+Math.floor(i/w),
 })));
}
